File _resolveFixtureFile(String filename) {
  final direct = File('test/fixtures/$filename');
  if (direct.existsSync()) return direct;
  final nested = File('vaultx_flutter/test/fixtures/$filename');
  if (nested.existsSync()) return nested;
  return direct;
}

String _flipByteInBase64(String base64Input, int index) {
  final bytes = Uint8List.fromList(base64Decode(base64Input));
  final targetIndex = index >= 0 ? index : (bytes.length + index);
  bytes[targetIndex] = bytes[targetIndex] ^ 0xff;
  return base64Encode(bytes);
}

void main() {
  final cryptoService = VaultCryptoService();

  group('Phase 2 Cryptographic Compatibility Gate', () {
    test(
      'Web TypeScript -> Flutter Dart: unlocks master & recovery wrappers and decrypts TS AES-256-GCM credentials',
      () async {
        final fixtureFile = _resolveFixtureFile('ts_interop_vectors.json');
        expect(
          fixtureFile.existsSync(),
          isTrue,
          reason: 'Expected ts_interop_vectors.json fixture generated by src/lib/crypto.ts',
        );

        final jsonMap =
            jsonDecode(fixtureFile.readAsStringSync()) as Map<String, dynamic>;
        final masterPassword = jsonMap['masterPassword'] as String;
        final recoveryKey = jsonMap['recoveryKey'] as String;
        final config = VaultMasterConfig.fromMap(
          jsonMap['configData'] as Map<String, dynamic>,
        );
        final credentials = (jsonMap['credentials'] as List<dynamic>)
            .cast<Map<String, dynamic>>();

        expect(config.kdfAlgorithm, VaultConstants.kdfAlgorithm);
        expect(config.kdfMemoryKiB, 65536);
        expect(config.kdfIterations, 3);
        expect(config.kdfParallelism, 1);

        // Unlock with Master Password (both isolate and direct execution)
        final keyFromMaster = await cryptoService.unlockVaultWithMasterPassword(
          masterPassword,
          config,
          useIsolate: true,
        );
        final keyFromMasterSync =
            await cryptoService.unlockVaultWithMasterPassword(
          masterPassword,
          config,
          useIsolate: false,
        );

        // Unlock with Recovery Key (both formatted and lowercase/whitespace variant)
        final keyFromRecovery = await cryptoService.unlockVaultWithRecoveryKey(
          recoveryKey.toLowerCase().replaceAll('-', ' '),
          config,
          useIsolate: false,
        );

        expect(
          await keyFromMaster.extractBytes(),
          equals(await keyFromMasterSync.extractBytes()),
        );
        expect(
          await keyFromMaster.extractBytes(),
          equals(await keyFromRecovery.extractBytes()),
        );

        for (final item in credentials) {
          final ciphertext = item['ciphertext'] as String;
          final iv = item['iv'] as String;
          final expected = CredentialPayload.fromJson(
            item['expectedPayload'] as Map<String, dynamic>,
          );

          expect(base64Decode(iv).length, VaultConstants.aesGcmNonceLengthBytes);

          final decryptedMaster = await cryptoService.decryptCredentialPayload(
            keyFromMaster,
            ciphertext,
            iv,
          );
          final decryptedRecovery = await cryptoService.decryptCredentialPayload(
            keyFromRecovery,
            ciphertext,
            iv,
          );

          expect(decryptedMaster, equals(expected));
          expect(decryptedRecovery, equals(expected));
        }
      },
    );

    test(
      'Flutter Dart -> Web TypeScript: initializes vault, generates Dart interop vectors, and supports rotation',
      () async {
        const syntheticMaster = 'Dart-Synthetic-VaultX-Master#2026!';
        final initResult = await cryptoService.initializeVaultKeys(
          syntheticMaster,
          userId: 'synthetic_dart_interop_user_001',
          kdfParams: const KdfParams(
            algorithm: VaultConstants.kdfAlgorithm,
            memoryKiB: 65536,
            iterations: 3,
            parallelism: 1,
          ),
          useIsolate: true,
        );

        expect(initResult.recoveryKey.startsWith('VX-'), isTrue);
        expect(
          cryptoService.normalizeRecoveryKey(initResult.recoveryKey).length,
          54, // 'VX' + 52 Base32 chars
        );

        const payload1 = CredentialPayload(
          title: 'Dart Synthetic Bank',
          username: 'dart.user@vaultx.test',
          password: 'DartGenerated!Password#2026',
          url: 'https://bank.vaultx.test',
          category: 'Finance',
          notes: 'Generated by Flutter VaultCryptoService for TS decryption.',
        );
        const payload2 = CredentialPayload(
          title: 'Dart Unicode — 東京 & "Quotes"',
          username: 'naïve+vault@example.org',
          password: 'P@ss\\w0rd"🔑&*()',
          url: 'https://example.org/auth?redirect=%2Fhome',
          category: 'Personal',
          notes: 'Line 1\nLine 2\tTab — ✓',
        );

        final enc1 = await cryptoService.encryptCredentialPayload(
          initResult.vaultKey,
          payload1,
        );
        final enc2 = await cryptoService.encryptCredentialPayload(
          initResult.vaultKey,
          payload2,
        );

        // Verify Dart round-trip via both Master Password and Recovery Key
        final unlockedMaster = await cryptoService.unlockVaultWithMasterPassword(
          syntheticMaster,
          initResult.configData,
          useIsolate: false,
        );
        final unlockedRecovery = await cryptoService.unlockVaultWithRecoveryKey(
          initResult.recoveryKey,
          initResult.configData,
          useIsolate: false,
        );

        expect(
          await cryptoService.decryptCredentialPayload(
            unlockedMaster,
            enc1.ciphertext,
            enc1.iv,
          ),
          equals(payload1),
        );
        expect(
          await cryptoService.decryptCredentialPayload(
            unlockedRecovery,
            enc2.ciphertext,
            enc2.iv,
          ),
          equals(payload2),
        );

        // Export dart_interop_vectors.json so `npx vitest run` verifies Dart -> TS decryption
        final dartVectorOutput = {
          'schemaVersion': 1,
          'generatedBy': 'vaultx_flutter VaultCryptoService (cryptography Argon2id + AES-256-GCM)',
          'kdfParams': const KdfParams().toJson(),
          'masterPassword': syntheticMaster,
          'recoveryKey': initResult.recoveryKey,
          'configData': initResult.configData.toConfigMap(),
          'credentials': [
            {
              'id': cryptoService.generateCredentialId(),
              'keyVersion': initResult.configData.keyVersion,
              'ciphertext': enc1.ciphertext,
              'iv': enc1.iv,
              'expectedPayload': payload1.toJson(),
            },
            {
              'id': cryptoService.generateCredentialId(),
              'keyVersion': initResult.configData.keyVersion,
              'ciphertext': enc2.ciphertext,
              'iv': enc2.iv,
              'expectedPayload': payload2.toJson(),
            },
          ],
        };

        final outFile = _resolveFixtureFile('dart_interop_vectors.json');
        outFile.parent.createSync(recursive: true);
        outFile.writeAsStringSync(
          '${const JsonEncoder.withIndent('  ').convert(dartVectorOutput)}\n',
        );

        // Verify Master Password rotation preserves KDF params & existing DEK
        const rotatedMaster = 'Dart-Rotated-Master#2026!';
        final rotated = await cryptoService.rotateMasterPasswordWrapper(
          recoveryKey: initResult.recoveryKey,
          newMasterPassword: rotatedMaster,
          config: initResult.configData,
          useIsolate: false,
        );
        expect(rotated.kdfMemoryKiB, 65536);
        expect(rotated.kdfIterations, 3);
        expect(rotated.kdfParallelism, 1);
        expect(rotated.keyVersion, 2);

        final rotatedConfig = VaultMasterConfig(
          userId: initResult.configData.userId,
          kdfAlgorithm: rotated.kdfAlgorithm,
          kdfMemoryKiB: rotated.kdfMemoryKiB,
          kdfIterations: rotated.kdfIterations,
          kdfParallelism: rotated.kdfParallelism,
          masterSalt: rotated.masterSalt,
          wrappedVaultKey: rotated.wrappedVaultKey,
          wrappedVaultKeyIv: rotated.wrappedVaultKeyIv,
          recoverySalt: initResult.configData.recoverySalt,
          recoveryWrappedVaultKey: initResult.configData.recoveryWrappedVaultKey,
          recoveryWrappedVaultKeyIv: initResult.configData.recoveryWrappedVaultKeyIv,
          recoveryKeyHint: initResult.configData.recoveryKeyHint,
          keyVersion: rotated.keyVersion,
        );

        await expectLater(
          () => cryptoService.unlockVaultWithMasterPassword(
            syntheticMaster,
            rotatedConfig,
            useIsolate: false,
          ),
          throwsA(isA<InvalidMasterPasswordException>()),
        );
        final keyAfterRotation = await cryptoService.unlockVaultWithMasterPassword(
          rotatedMaster,
          rotatedConfig,
          useIsolate: false,
        );
        expect(
          await cryptoService.decryptCredentialPayload(
            keyAfterRotation,
            enc1.ciphertext,
            enc1.iv,
          ),
          equals(payload1),
        );
      },
    );

    test(
      'rejects invalid credentials, tampered ciphertext/tag/IV, and generates unique 12-byte nonces',
      () async {
        final fixtureFile = _resolveFixtureFile('ts_interop_vectors.json');
        final jsonMap =
            jsonDecode(fixtureFile.readAsStringSync()) as Map<String, dynamic>;
        final masterPassword = jsonMap['masterPassword'] as String;
        final config = VaultMasterConfig.fromMap(
          jsonMap['configData'] as Map<String, dynamic>,
        );
        final credentials = (jsonMap['credentials'] as List<dynamic>)
            .cast<Map<String, dynamic>>();
        final firstCred = credentials.first;
        final ciphertext = firstCred['ciphertext'] as String;
        final iv = firstCred['iv'] as String;

        // Invalid master password
        await expectLater(
          () => cryptoService.unlockVaultWithMasterPassword(
            'Wrong-Master-Passphrase#99',
            config,
            useIsolate: false,
          ),
          throwsA(isA<InvalidMasterPasswordException>()),
        );

        // Invalid recovery key (wrong characters & too short)
        await expectLater(
          () => cryptoService.unlockVaultWithRecoveryKey(
            'VX-AAAA-BBBB-CCCC-DDDD-EEEE-FFFF-2222-3333-4444-5555-6666-7777-8888',
            config,
            useIsolate: false,
          ),
          throwsA(isA<InvalidRecoveryKeyException>()),
        );
        await expectLater(
          () => cryptoService.unlockVaultWithRecoveryKey(
            'VX-SHORT',
            config,
            useIsolate: false,
          ),
          throwsA(isA<InvalidRecoveryKeyException>()),
        );

        final vaultKey = await cryptoService.unlockVaultWithMasterPassword(
          masterPassword,
          config,
          useIsolate: false,
        );

        // Tampered ciphertext byte (byte 0)
        await expectLater(
          () => cryptoService.decryptCredentialPayload(
            vaultKey,
            _flipByteInBase64(ciphertext, 0),
            iv,
          ),
          throwsA(isA<CiphertextTamperedException>()),
        );

        // Tampered 16-byte authentication tag (last byte)
        await expectLater(
          () => cryptoService.decryptCredentialPayload(
            vaultKey,
            _flipByteInBase64(ciphertext, -1),
            iv,
          ),
          throwsA(isA<CiphertextTamperedException>()),
        );

        // Tampered 12-byte nonce/IV
        await expectLater(
          () => cryptoService.decryptCredentialPayload(
            vaultKey,
            ciphertext,
            _flipByteInBase64(iv, 0),
          ),
          throwsA(isA<CiphertextTamperedException>()),
        );

        // Malformed nonce length
        await expectLater(
          () => cryptoService.decryptCredentialPayload(
            vaultKey,
            ciphertext,
            base64Encode(Uint8List(8)),
          ),
          throwsA(isA<CiphertextTamperedException>()),
        );

        // Unique 12-byte nonces across repeated encryptions
        final payload = CredentialPayload.fromJson(
          firstCred['expectedPayload'] as Map<String, dynamic>,
        );
        final seenIvs = <String>{};
        for (var i = 0; i < 25; i++) {
          final enc = await cryptoService.encryptCredentialPayload(
            vaultKey,
            payload,
          );
          expect(base64Decode(enc.iv).length, 12);
          expect(seenIvs.contains(enc.iv), isFalse);
          seenIvs.add(enc.iv);
        }
      },
    );
  });
}
